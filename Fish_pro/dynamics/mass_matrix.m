function M = mass_matrix(q,param)

m = param.m;
L = param.L;
r = param.r;
I = param.I;

q1 = q(1); q2 = q(2); q3 = q(3);

c2 = cos(q2);
c3 = cos(q3);
c23 = cos(q2+q3);

M11 = I(1) + I(2) + I(3) ...
    + m(2)*(L(1)^2 + r(2)^2 + 2*L(1)*r(2)*c2) ...
    + m(3)*(L(1)^2 + L(2)^2 + r(3)^2 ...
    + 2*L(1)*L(2)*c2 ...
    + 2*L(2)*r(3)*c3 ...
    + 2*L(1)*r(3)*c23);

M22 = I(2) + I(3) ...
    + m(3)*(L(2)^2 + r(3)^2 + 2*L(2)*r(3)*c3);

M33 = I(3);

M12 = I(2)+I(3) ...
    + m(2)*(r(2)^2 + L(1)*r(2)*c2) ...
    + m(3)*(L(2)^2 + r(3)^2 ...
    + L(1)*L(2)*c2 ...
    + 2*L(2)*r(3)*c3 ...
    + L(1)*r(3)*c23);

M13 = I(3) ...
    + m(3)*(r(3)^2 + L(2)*r(3)*c3 + L(1)*r(3)*c23);

M23 = I(3) + m(3)*(r(3)^2 + L(2)*r(3)*c3);

M = [M11 M12 M13;
     M12 M22 M23;
     M13 M23 M33];
end
